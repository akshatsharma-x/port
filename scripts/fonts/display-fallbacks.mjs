#!/usr/bin/env node
/**
 * styles/font-fallbacks-display.css — metric-matched fallbacks for Hubot Sans at the widths the
 * display steps actually set (DESIGN.md §2.5: "a late font swap moves nothing").
 *
 * next/font derives a fallback from the font file's default instance — Hubot's is condensed
 * (wdth 75), so its fallback is Arial at 76% while the display steps run at 100–125% width: the
 * name re-wraps when the face arrives (measured: CLS 0.03 on a throttled first load). This
 * measures, in the installed Chrome, the baked face against Arial at each step's real width and
 * weight over a text corpus, and writes one fallback per step: size-adjust = the width ratio, the
 * vertical metrics matched so the baseline doesn't move — plus Hubot's ascent, descent and cap
 * height, which the display steps' cap trim is computed from (styles/type.css).
 *
 *   node scripts/fonts/display-fallbacks.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { chromium } from "@playwright/test";

const ROOT = new URL("../..", import.meta.url).pathname;
const tokens = readFileSync(`${ROOT}styles/tokens.css`, "utf8");
const token = (name) => {
  const m = new RegExp(`--${name}:\\s*([^;]+);`).exec(tokens);
  if (!m) throw new Error(`no --${name} in tokens.css`);
  return m[1].trim();
};
const STEPS = ["heading", "title", "display", "mega"].map((step) => ({ step, wdth: token(`wdth-${step}`), wght: token(`wght-${step}`) }));
const CORPUS = [
  "NOOR HALVORSEN",
  "SEND A SIGNAL",
  "RESEARCH & PUBLICATIONS",
  "Hi-fi rendering of lo-fi artifacts",
  "Interfaces for machine learning, and research on how people read them",
  "THE QUICK BROWN FOX JUMPS OVER THE LAZY DOG 0123456789",
  "The quick brown fox jumps over the lazy dog",
];
const font = readFileSync(`${ROOT}app/fonts/HubotSans-Variable.woff2`).toString("base64");

const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage();
await page.setContent(`<style>@font-face{font-family:Probe;src:url(data:font/woff2;base64,${font}) format("woff2");font-weight:200 900;font-stretch:75% 125%}</style><span id=s style="position:absolute;white-space:nowrap;font-size:100px">x</span>`);
await page.evaluate(() => document.fonts.load('700 100px Probe'));
const result = await page.evaluate(({ steps, corpus }) => {
  const s = document.getElementById("s");
  const width = (family, wght, wdth, text) => {
    s.style.fontFamily = family;
    s.style.fontWeight = wght;
    s.style.fontStretch = wdth;
    s.textContent = text;
    return s.getBoundingClientRect().width;
  };
  const c = document.createElement("canvas").getContext("2d");
  c.font = "700 100px Probe";
  const m = c.measureText("H");
  // the cap line as text-box-trim's `cap` edge reads it (OS/2 sCapHeight) — constant across Hubot's
  // instances (measured: 0.729 em at every step's wdth and wght)
  const box = document.createElement("div");
  box.style.cssText = "position:absolute;font:700 1000px Probe;line-height:1;text-box:trim-both cap alphabetic";
  box.textContent = "H";
  document.body.append(box);
  const cap = box.getBoundingClientRect().height / 1000;
  box.remove();
  const v = { ascent: m.fontBoundingBoxAscent / 100, descent: m.fontBoundingBoxDescent / 100, cap };
  return {
    vertical: v,
    steps: steps.map(({ step, wdth, wght }) => {
      const ratios = corpus.map((t) => width("Probe", wght, wdth, t) / width("Arial", wght, "100%", t));
      return { step, wdth, wght, ratio: ratios.reduce((a, b) => a + b, 0) / ratios.length, spread: [Math.min(...ratios), Math.max(...ratios)] };
    }),
  };
}, { steps: STEPS, corpus: CORPUS });
await browser.close();

const pct = (x) => `${(x * 100).toFixed(3)}%`;
const faces = result.steps
  .map(
    (s) => `/* ${s.step}: wdth ${s.wdth}, wght ${s.wght} — Hubot is ${s.ratio.toFixed(4)}× Arial (corpus spread ${s.spread[0].toFixed(3)}–${s.spread[1].toFixed(3)}) */
@font-face {
  font-family: "Hubot Sans Fallback ${s.step}";
  src: local("Arial"), local("ArialMT"), local("Liberation Sans"), local("Arimo");
  size-adjust: ${pct(s.ratio)};
  ascent-override: ${pct(result.vertical.ascent / s.ratio)};
  descent-override: ${pct(result.vertical.descent / s.ratio)};
  line-gap-override: 0%;
}`,
  )
  .join("\n");
writeFileSync(
  `${ROOT}styles/font-fallbacks-display.css`,
  `/* GENERATED by scripts/fonts/display-fallbacks.mjs — do not edit by hand.
   Hubot Sans fallbacks, one per display step, matched at the width and weight that step sets
   (next/font's own fallback matches the file's condensed default instance instead). The
   vertical metrics are Hubot's (ascent ${result.vertical.ascent.toFixed(3)} em, descent ${result.vertical.descent.toFixed(3)} em), divided by size-adjust. */
${faces}

/* Hubot's own vertical metrics, em. The display steps trim to its cap line and baseline with these
   (styles/type.css), not with the drawing face's: no descriptor can match a fallback's cap height,
   and a width-matched Arial's caps are 1.2–1.3× Hubot's, so a box trimmed by the face in use
   changed height when Hubot arrived. */
:root {
  --display-ascent: ${result.vertical.ascent.toFixed(4)};
  --display-descent: ${result.vertical.descent.toFixed(4)};
  --display-cap: ${result.vertical.cap.toFixed(4)};
}
`,
);
console.log(result.steps.map((s) => `${s.step}: ×${s.ratio.toFixed(4)} (${s.spread.map((x) => x.toFixed(3)).join("–")})`).join("\n"));
